def build_fastfetch_conf(c):
    keys = hex_to_ansi(c["accent"])
    title = hex_to_ansi(c["accent2"])
    logo1 = hex_to_ansi(c["accent"])
    logo2 = hex_to_ansi(c["accent2"])
    data = {
        "$schema": "https://github.com/fastfetch-cli/fastfetch/raw/dev/doc/json_schema.json",
        # Compact "small" logo: the full auto logo (~40 cols wide) overflowed and
        # garbled the output whenever a terminal was tiled narrow (several open at
        # once). The small logo keeps the greeting clean down to half-width tiles.
        "logo": {"type": "small", "padding": {"top": 1, "right": 1},
                 "color": {"1": logo1, "2": logo2}},
        "display": {"separator": "  ", "color": {"keys": keys, "title": title}},
        "modules": [
            {"type": "title", "color": {"user": keys, "at": title, "host": keys}},
            {"type": "separator", "string": "─"},
            {"type": "os", "key": "OS"},
            {"type": "kernel", "key": "Kernel"},
            {"type": "uptime", "key": "Uptime"},
            {"type": "packages", "key": "Packages"},
            {"type": "shell", "key": "Shell"},
            {"type": "terminal", "key": "Terminal"},
            {"type": "wm", "key": "WM"},
            # Compact CPU/disk formats: full defaults ("… (32) @ 3.19 GHz",
            # "… - ext4") overran narrow tiled terminals. Drop cores/freq/fs.
            {"type": "cpu", "key": "CPU", "format": "{name}"},
            {"type": "gpu", "key": "GPU", "format": "{name}"},
            {"type": "memory", "key": "Memory"},
            {"type": "disk", "key": "Disk", "format": "{size-used} / {size-total} ({size-percentage})"},
            "break",
            {"type": "colors", "symbol": "circle"},
        ],
    }
    return json.dumps(data, indent=2) + "\n"


def ghostty_reload():
    """Ghostty reloads its config on SIGUSR2 -> open terminals re-theme live."""
    if shutil.which("pkill"):
        subprocess.run(["pkill", "-SIGUSR2", "ghostty"], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def regenerate_terminal(cfg):
    colors, _ = load_theme(cfg)
    ghostty_changed = atomic_write(GHOSTTY_CONF, build_ghostty_conf(cfg, colors))
    atomic_write(FISH_THEME, build_fish_theme(colors))
    atomic_write(FASTFETCH_CONF, build_fastfetch_conf(colors))
    # Only signal Ghostty when its config genuinely changed (theme colours or
    # font). A wallpaper change never touches the ghostty config bytes, so we
    # skip the SIGUSR2 and it doesn't flash "config reloaded" across every open
    # terminal. A real theme colour change still reloads so the colours apply.
    if ghostty_changed:
        ghostty_reload()
        log("regenerated ghostty/fish/fastfetch theme + signalled Ghostty reload")
    else:
        log("regenerated fish/fastfetch theme (ghostty config unchanged; no reload)")


def cursor_theme_name(cfg):
    """Nombre del tema XCursor para la elección de appearance.cursorTheme.

    NUNCA devuelve cadena vacía: un id desconocido cae en el de fábrica. Sin
    tema fijado Hyprland usa su cursor embebido, que tiene forma de su logo."""
    appearance = cfg.get("appearance", {}) or {}
    choice = str(appearance.get("cursorTheme", CURSOR_FALLBACK)).strip().lower()
    choice = CURSOR_ALIASES.get(choice, choice)
    return CURSOR_THEMES.get(choice, CURSOR_THEMES[CURSOR_FALLBACK])


def apply_cursor_live(cfg):
    """Aplica el cursor al compositor YA corriendo.

    `hl.env` en el fichero generado solo sirve para el siguiente arranque: un
    proceso vivo no re-lee su entorno. Hyprland expone `hyprctl setcursor` para
    justo esto. Es best-effort: si falla (o si no hay compositor, p. ej. en el
    --oneshot de una instalación), el env generado lo arregla en el siguiente
    inicio de sesión."""
    theme = cursor_theme_name(cfg)
    try:
        subprocess.run(["hyprctl", "setcursor", theme, CURSOR_SIZE],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                       timeout=5, check=False)
    except (OSError, subprocess.SubprocessError):
        pass


def _write_greeter_fragment(path, content, label):
    """Escribe un fragmento Lua del greeter si se puede y si cambió.

    Mismo contrato que sync_greeter_theme: compare-first y salida silenciosa si
    no hay permiso. En Arch el directorio es de root, así que esto no hace nada
    y el teclado del greeter lo sigue poniendo install.sh /
    vexyon-greeter-sync-theme (con sudo) igual que antes — no hay cambio de
    comportamiento allí. En NixOS el directorio es del usuario y el greeter
    queda sincronizado solo, sin escalar privilegios ni pedir nada."""
    try:
        if os.path.isfile(path):
            if not os.access(path, os.W_OK):
                return
            with open(path) as f:
                if f.read() == content:
                    return
        elif not os.access(os.path.dirname(path), os.W_OK):
            return
        with open(path, "w") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        log(f"greeter {label} snapshot synced")
    except OSError as e:
        log(f"greeter {label} sync skipped ({e})")


def sync_greeter_input(cfg):
    """Teclado del greeter = teclado de la sesión.

    Sin esto la pantalla de login se queda en la distribución con la que se
    creó y una contraseña con caracteres que cambian de sitio entre
    distribuciones es INTECLEABLE — el usuario no puede entrar.

    Solo se escribe si el usuario tiene una elección EXPLÍCITA en shell.json:
    si la clave no está, el defecto lo pone el sistema (el módulo de NixOS lo
    pasa por entorno al kiosco) y machacarlo aquí con un "us" inventado
    volvería a romper justo lo que esto arregla."""
    behavior = cfg.get("behavior", {}) or {}
    if "keyboardLayout" not in behavior:
        return
    kb = str(behavior.get("keyboardLayout", "")).strip()
    if not kb or not all(c.isalnum() or c in ",_-" for c in kb):
        return
    kbv = str(behavior.get("keyboardVariant", "")).strip()
    if not all(c.isalnum() or c in ",_-" for c in kbv):
        kbv = ""
    content = (
        "-- Vexyon — greeter input (GENERATED by vexyon-bridge)\n"
        f"hl.config({{ input = {{ kb_layout = {lua_str(kb)}, "
        f"kb_variant = {lua_str(kbv)} }} }})\n"
    )
    _write_greeter_fragment(GREETER_INPUT_LUA, content, "keyboard")


def sync_greeter_cursor(cfg):
    """Cursor del greeter = cursor de la sesión (misma pinta antes y después
    del login). Mismo patrón de snapshot que el tema."""
    content = (
        "-- Vexyon — greeter cursor (GENERATED by vexyon-bridge)\n"
        f"hl.env(\"XCURSOR_THEME\", {lua_str(cursor_theme_name(cfg))})\n"
        f"hl.env(\"XCURSOR_SIZE\", {lua_str(CURSOR_SIZE)})\n"
    )
    _write_greeter_fragment(GREETER_CURSOR_LUA, content, "cursor")


def sync_greeter_theme(cfg):
    """Mirror the active theme JSON into the greeter's /etc snapshot.

    The greeter runs as the `greetd` user before login and cannot read
    ~/.config; it reads /etc/greetd/vexyon-greeter/theme.json instead. The
    snapshot file is user-owned (seeded that way by install.sh) so this write
    needs no privilege escalation. The directory stays root-owned, so no
    temp+rename here: compare-first in-place write. The greeter only parses
    the file once at boot and falls back to its embedded palette on a bad
    parse, so the non-atomic write is harmless."""
    active = (cfg.get("theme", {}) or {}).get("active", "crimson-voltage")
    src = os.path.join(THEMES_DIR, active + ".json")
    if not os.path.isfile(src) or not os.path.isfile(GREETER_THEME):
        return
    if not os.access(GREETER_THEME, os.W_OK):
        return  # pre-user-ownership install; re-running install.sh fixes it
    try:
        with open(src) as f:
            content = f.read()
        parsed = json.loads(content)  # never overwrite a good snapshot with garbage
        if not isinstance(parsed.get("colors"), dict):
            log(f"greeter theme sync skipped: '{active}' has no colors dict")
            return
        with open(GREETER_THEME) as f:
            if f.read() == content:
                return
        with open(GREETER_THEME, "w") as f:
            f.write(content)
            f.flush()
            os.fsync(f.fileno())
        log(f"greeter theme snapshot synced -> {active}")
    except (OSError, ValueError) as e:
        log(f"greeter theme sync skipped ({e})")


def sync_color_scheme(cfg):
    """Expose the active theme's light/dark as the freedesktop color-scheme.

    Writes `org.gnome.desktop.interface color-scheme` — the backing key the
    portal's Settings backend (xdg-desktop-portal-gtk, the declared fallback
    in hyprland-portals.conf) reads. xdg-desktop-portal then broadcasts it to
    apps as `org.freedesktop.appearance color-scheme`; browsers forward it to
    web pages as the `prefers-color-scheme` media query. Event-driven: runs
    only inside regenerate() (shell.json change); compare-first so wallpaper/
    keybind regenerates and already-correct values are a no-op. Sites with
    their own theme toggle ignore the preference by design — out of our hands."""
    if not shutil.which("gsettings"):
        return  # glib2 missing (non-standard install); nothing to sync into
    _, is_dark = load_theme(cfg)
    want = "prefer-dark" if is_dark else "prefer-light"
    try:
        cur = subprocess.run(
            ["gsettings", "get", "org.gnome.desktop.interface", "color-scheme"],
            capture_output=True, text=True, timeout=5).stdout.strip().strip("'")
        if cur == want:
            return
        subprocess.run(
            ["gsettings", "set", "org.gnome.desktop.interface", "color-scheme", want],
            check=False, timeout=5,
            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        log(f"color-scheme -> {want}")
    except Exception as e:
        log(f"color-scheme sync skipped ({e})")


def hyprctl_reload():
    if not shutil.which("hyprctl"):
        log("hyprctl not found; skipping reload (not in a Hyprland session?)")
        return
    try:
        subprocess.run(["hyprctl", "reload"], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=10)
        log("hyprctl reload triggered")
    except Exception as e:
        log(f"hyprctl reload failed: {e}")


def regenerate(cfg, reload=True):
    atomic_write(KEYBINDS_LUA, build_keybinds_lua(cfg))
    atomic_write(SETTINGS_LUA, build_settings_lua(cfg))
    atomic_write(MONITORS_LUA, build_monitors_lua(cfg))
    log(f"regenerated {os.path.basename(KEYBINDS_LUA)} + {os.path.basename(SETTINGS_LUA)} + {os.path.basename(MONITORS_LUA)}")
    regenerate_terminal(cfg)
    sync_greeter_theme(cfg)
    sync_greeter_input(cfg)
    sync_greeter_cursor(cfg)
    sync_color_scheme(cfg)
    if reload:
        hyprctl_reload()
    # Después del reload: `hyprctl reload` NO re-lee el entorno de un proceso ya
    # vivo, así que el hl.env generado solo valdría para el siguiente arranque.
    # Esta llamada es la que hace que el cambio de cursor se vea sin cerrar
    # sesión. Idempotente: setcursor con el mismo tema no parpadea.
    apply_cursor_live(cfg)


def main():
    oneshot = "--oneshot" in sys.argv
    cfg = load_config()
    if cfg is None:
        log("no valid config on startup; nothing to generate")
        if oneshot:
            sys.exit(1)
    else:
        # On the very first generation don't reload if oneshot from installer
        regenerate(cfg, reload=not oneshot)

    if oneshot:
        return

    last_mtime = os.path.getmtime(SHELL_JSON) if os.path.exists(SHELL_JSON) else 0
    last_good = cfg
    log("watching shell.json for changes...")
    while True:
        time.sleep(POLL_INTERVAL)
        try:
            mtime = os.path.getmtime(SHELL_JSON)
        except FileNotFoundError:
            continue
        if mtime == last_mtime:
            continue
        last_mtime = mtime
        new_cfg = load_config()
        if new_cfg is None:
            continue  # malformed; keep last good, wait for next save
        if new_cfg == last_good:
            continue  # touched but identical
        last_good = new_cfg
        log("shell.json changed -> regenerating + reloading")
        regenerate(new_cfg, reload=True)


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        pass

def log(msg):
    print(f"[vexyon-bridge] {msg}", flush=True)


def load_config():
    """Read shell.json. Returns dict or None on failure (caller keeps last good)."""
    try:
        with open(SHELL_JSON, "r") as f:
            return json.load(f)
    except FileNotFoundError:
        log(f"config not found: {SHELL_JSON}")
        return None
    except json.JSONDecodeError as e:
        log(f"invalid JSON in shell.json ({e}); keeping last good config")
        return None


def atomic_write(path, content):
    """Write content to path atomically (temp file in same dir + os.replace).

    Returns True if the on-disk content actually changed (or the file was
    created), False if it already matched byte-for-byte. Callers use this to
    avoid signalling a consumer that nothing relevant changed — e.g. Ghostty
    would pop a "config reloaded" toast on SIGUSR2 even when the rewrite was
    a no-op (a wallpaper change leaves the terminal config identical)."""
    try:
        with open(path, "r") as f:
            if f.read() == content:
                return False
    except (FileNotFoundError, OSError):
        pass
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(content)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)
    return True


def fmt_scale(s):
    """1 -> '1', 1.25 -> '1.25' (trim trailing zeros; Hyprland wants a clean float)."""
    try:
        n = float(s)
    except (TypeError, ValueError):
        return "1"
    if n <= 0:
        return "1"
    return ("%f" % n).rstrip("0").rstrip(".") or "1"


# ============================================================================
#  Emisores Lua (Hyprland >= 0.55; hyprlang desaparece en 0.57). Reglas de
#  emisión "lean" (HYPRLAND_LUA_MIGRATION_PLAN.md): UNA llamada hl.config por
#  regeneración, bucles Lua para los binds de workspace, closures hl.dsp.*
#  directas sin funciones envoltorio. Formas verificadas EN VIVO, no deducidas:
#  follow=false para mover sin seguir el foco, bind SIN opts para el equivalente
#  de bindm, y match = regex para las layer rules.
# ============================================================================

def lua_str(s):
    """Arbitrary config text -> safe double-quoted Lua string literal."""
    out = (str(s).replace("\\", "\\\\").replace('"', '\\"')
           .replace("\n", "\\n").replace("\r", "\\r"))
    return f'"{out}"'


def lua_key(mods, key):
    """['SUPER','SHIFT'], 'S' -> Lua key string 'SUPER + SHIFT + S'."""
    return " + ".join(list(mods) + [str(key)])


_LUA_DIRS = {"l": "left", "r": "right", "u": "up", "d": "down"}


def lua_ws(p):
    """Workspace selector: numeric stays a Lua number, else quoted string."""
    p = str(p).strip()
    return p if p.isdigit() else lua_str(p)


def lua_dispatcher(disp, params):
    """Classic dispatcher string -> hl.dsp.* call, or None if unknown.
    Solo los dispatchers que Vexyon usa en shell.json (Keybind Editor incluido);
    uno desconocido se salta con log, igual que una action desconocida — las
    tablas de opts de Lua IGNORAN claves inválidas sin error, así que aquí no
    se inventa nada: cada forma está verificada contra el source de 0.56.1."""
    params = (params or "").strip()
    if disp == "killactive":
        return "hl.dsp.window.close()"
    if disp == "togglefloating":
        return 'hl.dsp.window.float({ action = "toggle" })'
    if disp == "fullscreen":
        mode = "maximized" if params == "1" else "fullscreen"
        return f'hl.dsp.window.fullscreen({{ mode = "{mode}" }})'
    if disp == "togglespecialworkspace":
        return (f"hl.dsp.workspace.toggle_special({lua_str(params)})"
                if params else "hl.dsp.workspace.toggle_special()")
    if disp == "movefocus" and params in _LUA_DIRS:
        return f'hl.dsp.focus({{ direction = "{_LUA_DIRS[params]}" }})'
    if disp == "swapwindow" and params in _LUA_DIRS:
        return f'hl.dsp.window.swap({{ direction = "{_LUA_DIRS[params]}" }})'
    if disp == "workspace":
        return f"hl.dsp.focus({{ workspace = {lua_ws(params)} }})"
    if disp == "movetoworkspace":
        return f"hl.dsp.window.move({{ workspace = {lua_ws(params)} }})"
    if disp == "movetoworkspacesilent":
        return f"hl.dsp.window.move({{ workspace = {lua_ws(params)}, follow = false }})"
    if disp == "exit":
        return "hl.dsp.exit()"
    return None


# Acciones de mouseBinds (bindm clásico). En Lua el equivalente es un bind
# NORMAL (sin opts) con el dispatcher interactivo: se dispara al PULSAR y el
# arrastre sigue al puntero hasta soltar, igual que bindm.
#
# OJO — verificado en vivo, no deducido: `{ drag = true }` NO es el equivalente
# de bindm. En KeybindManager.cpp un bind con `drag` implica `release = true` y
# solo se dispara al SOLTAR el botón y habiendo superado drag_threshold, o sea
# justo cuando ya no se puede arrastrar nada. Y `{ mouse = true }` (lo que trae
# el ejemplo oficial /usr/share/hypr/hyprland.lua) es INERTE: kb.mouse nunca se
# asigna desde las opts en el binding Lua de 0.56.1, solo se lee en una
# validación. Por eso el ejemplo funciona: equivale a un bind sin opts.
_LUA_MOUSE = {
    "movewindow": "hl.dsp.window.drag()",
    "resizewindow": "hl.dsp.window.resize()",
}


def build_keybinds_lua(cfg):
    lines = [LUA_HEADER]
    lines.append("-- --- Static core mouse binds ---\n")
    lines.append('hl.gesture({ fingers = 3, direction = "horizontal", action = "workspace" })\n')
    for mb in cfg.get("mouseBinds", []):
        dsp = _LUA_MOUSE.get(mb.get("action"))
        if not dsp:
            log(f"unknown mouse action '{mb.get('action')}' for '{mb.get('id')}', skipping")
            continue
        keys = lua_key(mb.get("mods", []), mb["button"])
        lines.append(f"hl.bind({lua_str(keys)}, {dsp})\n")
    lines.append("\n-- --- Named action binds ---\n")

    for kb in cfg.get("keybinds", []):
        keys = lua_key(kb.get("mods", []), kb["key"])
        action = kb["action"]
        arg = kb.get("arg", "")
        if action == "exec":
            dsp = f"hl.dsp.exec_cmd({lua_str(arg)})"
        elif action == "global":
            # Quickshell GlobalShortcut: appid 'quickshell', name = arg
            dsp = f"hl.dsp.global({lua_str('quickshell:' + arg)})"
        elif action == "dispatch":
            parts = arg.split(" ", 1)
            dsp = lua_dispatcher(parts[0], parts[1] if len(parts) == 2 else "")
            if not dsp:
                log(f"no Lua mapping for dispatcher '{arg}' (keybind '{kb.get('id')}'), skipping")
                continue
        else:
            log(f"unknown action '{action}' for keybind '{kb.get('id')}', skipping")
            continue
        # Flags de shell.json: 'l' (locked) y 'e' (repeating);
        # cualquier otro carácter se descarta.
        flags = str(kb.get("flags", ""))
        opts = []
        if "l" in flags:
            opts.append("locked = true")
        if "e" in flags:
            opts.append("repeating = true")
        optstr = f", {{ {', '.join(opts)} }}" if opts else ""
        desc = kb.get("desc", "")
        comment = f"  -- {desc}" if desc else ""
        lines.append(f"hl.bind({lua_str(keys)}, {dsp}{optstr}){comment}\n")

    # --- Workspace switch / move binds: bucles Lua, no 20 líneas desenrolladas ---
    lines.append("\n-- --- Workspace binds (generated from workspaceCount) ---\n")
    count = cfg.get("layout", {}).get("workspaceCount", 10)
    count = max(1, min(count, 10))
    km = cfg.get("keybindMods", {})
    sw = lua_str(" + ".join(km.get("workspaceSwitch", ["SUPER"])) + " + ")
    mv = lua_str(" + ".join(km.get("workspaceMove", ["SUPER", "SHIFT"])) + " + ")
    lines.append(f"for i = 1, {count} do\n")
    lines.append("    local key = i % 10\n")
    lines.append(f"    hl.bind({sw} .. key, hl.dsp.focus({{ workspace = i }}))\n")
    lines.append("    -- NON-silent move: the user FOLLOWS the window to the target workspace.\n")
    lines.append(f"    hl.bind({mv} .. key, hl.dsp.window.move({{ workspace = i }}))\n")
    lines.append("end\n")
    return "".join(lines)


def build_monitors_lua(cfg):
    """Source of truth is shell.json displays.activeProfile;
    emits hl.monitor tables. Empty profile emits nothing so the catch-all
    hl.monitor in hyprland.lua stays in effect (later calls accumulate)."""
    lines = [LUA_HEADER]
    lines.append("-- Generated from shell.json displays.activeProfile.\n")
    disp = cfg.get("displays", {}) or {}
    active = disp.get("activeProfile", "")
    profile = None
    for p in disp.get("profiles", []) or []:
        if p.get("name") == active:
            profile = p
            break
    if not profile or not profile.get("monitors"):
        # Sin perfil activo la geometría la pone hyprland.lua, pero la asignación
        # de workspaces es independiente del perfil: se emite igualmente.
        lines.append("-- (no active profile — hyprland.lua default applies)\n")
        lines.append(build_default_workspaces_lua(cfg))
        return "".join(lines)
    lines.append(f"-- Active profile: {active}\n")
    for name, c in profile["monitors"].items():
        lines.append(lua_monitor_call(name, c) + "\n")
    lines.append(build_default_workspaces_lua(cfg))
    return "".join(lines)


def build_default_workspaces_lua(cfg):
    """Default workspace per monitor, from displays.defaultWorkspaces.

    Keyed by the monitor's EDID description (make + model + serial), never by
    connector: on the real tower the port order does not match the physical
    order (DP-1 left, DP-3 middle, DP-2 right), and two of the panels are the
    same model, so only the serial-bearing description identifies them.

    A rule whose monitor is not currently connected is accepted by Hyprland
    without error and simply matches nothing, so the whole map is emitted
    unconditionally — the assignment comes back by itself on reconnect.
    Empty map emits nothing, i.e. stock Hyprland behaviour."""
    dws = (cfg.get("displays", {}) or {}).get("defaultWorkspaces", {}) or {}
    if not dws:
        return ""
    out = ["\n-- --- Default workspace per monitor (stable EDID description) ---\n"]
    for key, ws in sorted(dws.items()):
        try:
            n = int(ws)
        except (TypeError, ValueError):
            continue
        if n <= 0:
            continue
        out.append(lua_workspace_rule(key, n) + "\n")
    return "".join(out)


def lua_workspace_rule(key, ws):
    """Mirrors Displays.wsRuleCall() in QML so live-apply and the persisted
    config agree. `workspace` must be a string (hl.meta.lua stub)."""
    sel = key if ("-" in key and " " not in key) else f"desc:{key}"
    return (f"hl.workspace_rule({{ workspace = {lua_str(str(ws))}, "
            f"monitor = {lua_str(sel)}, default = true }})")


def lua_monitor_call(name, c):
    """Mirrors Displays.monCall() in QML so live-apply and the persisted
    config agree field by field."""
    if c.get("enabled") is False:
        return f"hl.monitor({{ output = {lua_str(name)}, disabled = true }})"
    mode = f"{c.get('resolution', 'preferred')}@{c.get('refresh', 60)}"
    pos = f"{int(c.get('x', 0))}x{int(c.get('y', 0))}"
    fields = [
        f"output = {lua_str(name)}",
        f"mode = {lua_str(mode)}",
        f"position = {lua_str(pos)}",
        f"scale = {lua_str(fmt_scale(c.get('scale', 1)))}",
        f"transform = {int(c.get('transform', 0))}",
        f"vrr = {int(c.get('vrr', 0))}",
    ]
    if int(c.get("bitdepth", 8)) == 10:
        fields.append("bitdepth = 10")
    return f"hl.monitor({{ {', '.join(fields)} }})"


def build_settings_lua(cfg):
    """ONE hl.config call + the two bar
    layer rules. The col.* gradient uses the Lua table form
    { colors = {...}, angle = 45 } (verified against the shipped example)."""
    layout = cfg.get("layout", {})
    behavior = cfg.get("behavior", {})
    appearance = cfg.get("appearance", {})
    gaps_in = layout.get("gapsIn", 4)
    gaps_out = layout.get("gapsOut", 10)
    border = layout.get("borderSize", 2)
    rounding = layout.get("roundingHypr", 12)
    ffm = 1 if behavior.get("focusFollowsMouse", True) else 0
    kb = str(behavior.get("keyboardLayout", "us")).strip() or "us"
    if not all(c.isalnum() or c in ",_-" for c in kb):
        kb = "us"
    kbv = str(behavior.get("keyboardVariant", "")).strip()
    if not all(c.isalnum() or c in ",_-" for c in kbv):
        kbv = ""
    bar_blur = appearance.get("barBlur", True) is not False
    intensity = appearance.get("barBlurIntensity", 24)
    blur_size = max(2, min(int(intensity / 4), 14))
    colors, _ = load_theme(cfg)
    body = (
        LUA_HEADER
        + "hl.config({\n"
        + "    general = {\n"
        + f"        gaps_in = {gaps_in},\n"
        + f"        gaps_out = {gaps_out},\n"
        + f"        border_size = {border},\n"
        + "        col = {\n"
        + f"            active_border = {{ colors = {{ \"rgba({theme_hex(colors, 'accent')}ff)\", \"rgba({theme_hex(colors, 'accent2')}ff)\" }}, angle = 45 }},\n"
        + f"            inactive_border = \"rgba({theme_hex(colors, 'surface1')}aa)\",\n"
        + "        },\n"
        + "    },\n"
        + "    decoration = {\n"
        + f"        rounding = {rounding},\n"
        + "        blur = {\n"
        + f"            enabled = {'true' if bar_blur else 'false'},\n"
        + f"            size = {blur_size},\n"
        + "            passes = 3,\n"
        + "        },\n"
        + "    },\n"
        + "    input = {\n"
        + f"        kb_layout = {lua_str(kb)},\n"
        + f"        kb_variant = {lua_str(kbv)},\n"
        + f"        follow_mouse = {ffm},\n"
        + "    },\n"
        + "})\n"
    )
    # Cursor. Va como env porque XCURSOR_THEME es lo que lee Hyprland (y todo
    # cliente XCursor) al arrancar; el cambio EN CALIENTE lo hace aparte
    # `hyprctl setcursor`, porque un env nuevo no llega a un compositor que ya
    # está corriendo. SIEMPRE se emite: dejar XCURSOR_THEME sin fijar es lo que
    # saca el cursor embebido de Hyprland (con forma de su logo).
    body += (
        "\n-- Cursor (appearance.cursorTheme). El cambio en vivo lo aplica el\n"
        "-- bridge con `hyprctl setcursor`; esto es lo que persiste al reiniciar.\n"
        f"hl.env(\"XCURSOR_THEME\", {lua_str(cursor_theme_name(cfg))})\n"
        f"hl.env(\"XCURSOR_SIZE\", {lua_str(CURSOR_SIZE)})\n"
    )
    if bar_blur:
        body += (
            "\n-- Blur SOLO en la barra (appearance.barBlur). match = regex, el mismo\n"
            "-- motor que las layerrules clásicas (verificado en el source 0.56.1).\n"
            'hl.layer_rule({ name = "vexyon-bar-blur", match = { namespace = "^(vexyon-bar)$" }, blur = true })\n'
            'hl.layer_rule({ name = "vexyon-bar-alpha", match = { namespace = "^(vexyon-bar)$" }, ignore_alpha = 0.2 })\n'
        )
    return body


